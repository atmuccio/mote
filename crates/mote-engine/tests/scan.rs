//! End-to-end scans with a fake plugin over plain directories and real git repositories.

mod common;

use common::{commit_all, dup_body, git, init_repo, opts, scanner, write};
use mote_core::{Finding, FindingStatus, Severity};
use mote_engine::analyze::SkipReason;
use mote_engine::git::clone_remote;
use mote_engine::result::{FileStatus, ScanResult};
use mote_engine::scan::{discover_config, ScanOptions, SourceSpec};
use std::sync::atomic::Ordering;

fn ids(r: &ScanResult) -> Vec<(String, u32, String)> {
    r.findings
        .iter()
        .map(|f| (f.path.clone(), f.range.start_line, f.rule_id.clone()))
        .collect()
}

fn find<'a>(r: &'a ScanResult, path: &str, rule: &str) -> Vec<&'a Finding> {
    r.findings
        .iter()
        .filter(|f| f.path == path && f.rule_id == rule)
        .collect()
}

fn status_of(r: &ScanResult, path: &str) -> FileStatus {
    r.files
        .iter()
        .find(|f| f.path == path)
        .map(|f| f.status)
        .unwrap_or_else(|| panic!("no file {path}"))
}

#[test]
fn directory_scan_findings_measures_and_skips() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    write(
        root,
        "src/a.fk",
        "fn big cog=20\n  LOUD\n  // TODO: tidy\nend\n",
    );
    write(root, "src/test/t.fk", "LOUD\nMAGIC\n");
    write(root, "gen/g.fk", "LOUD\n");
    write(
        root,
        "src/gen.fk",
        "// Code generated by tool. DO NOT EDIT.\nLOUD\n",
    );
    write(root, "ignored/i.fk", "LOUD\n");
    write(root, ".gitignore", "ignored/\n");
    write(root, "README.md", "not a source file\n");
    let yaml = "exclude: [\"gen/**\"]\ntest_rules: { fk/magic: off }\n";
    let (s, _) = scanner(root, yaml);
    let r = s.scan(&opts(SourceSpec::Directory, None)).unwrap();

    assert_eq!(
        ids(&r),
        vec![
            ("src/a.fk".into(), 1, "fk/cognitive-complexity".into()),
            ("src/a.fk".into(), 2, "fk/loud".into()),
            ("src/a.fk".into(), 3, "fk/todo-comment".into()),
            ("src/test/t.fk".into(), 1, "fk/loud".into()),
        ]
    );
    assert_eq!(status_of(&r, "gen/g.fk"), FileStatus::Skipped);
    let skipped: Vec<(&str, Option<SkipReason>)> = r
        .files
        .iter()
        .filter(|f| f.status == FileStatus::Skipped)
        .map(|f| (f.path.as_str(), f.skip_reason))
        .collect();
    assert_eq!(
        skipped,
        vec![
            ("gen/g.fk", Some(SkipReason::Excluded)),
            ("src/gen.fk", Some(SkipReason::Generated))
        ]
    );
    assert!(
        r.files.iter().all(|f| f.path != "ignored/i.fk"),
        "gitignored files are not discovered"
    );
    assert!(
        r.files
            .iter()
            .find(|f| f.path == "src/test/t.fk")
            .unwrap()
            .is_test
    );
    assert_eq!(r.measures.total.files, 2);
    assert_eq!(r.measures.total.functions, 1);
    assert_eq!(r.measures.total.lines, 6);
    assert_eq!(r.stats.files_seen, 6);
    assert_eq!(r.stats.files_matched, 4);
    // no base: the gate's severity condition applies to all findings (none HIGH here)
    assert!(r.gate.passed);
    assert_eq!(r.gate.conditions[0].name, "findings");
    assert!(r
        .rules
        .iter()
        .any(|ri| ri.id == "fk/cognitive-complexity" && !ri.description.is_empty()));
    let cog = find(&r, "src/a.fk", "fk/cognitive-complexity")[0];
    assert_eq!(cog.value, Some(20.0));
    assert_eq!(cog.id.len(), 12);
}

/// Estimated effort (threshold findings scaled by the limit in force), the main/test split and the
/// directory rollups.
#[test]
fn effort_splits_and_directory_rollups() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    write(
        root,
        "src/main/a.fk",
        "fn big cog=45\n  LOUD\n  // TODO: tidy\nend\n",
    );
    write(root, "src/main/deep/b.fk", "INCUB\n");
    write(root, "src/test/t.fk", "LOUD\n");
    write(root, "top.fk", "LOUD\n");
    let (s, _) = scanner(root, "");
    let r = s.scan(&opts(SourceSpec::Directory, None)).unwrap();
    let effort = |r: &ScanResult, path: &str| {
        r.files
            .iter()
            .find(|f| f.path == path)
            .unwrap()
            .effort_minutes
    };
    // Cognitive complexity 45 against the default limit of 15: 3 × 10 minutes; LOUD 5; TODO 10.
    assert_eq!(effort(&r, "src/main/a.fk"), 30 + 5 + 10);
    // Incubating rules report, but their findings don't count toward effort.
    assert_eq!(find(&r, "src/main/deep/b.fk", "fk/incubating").len(), 1);
    assert_eq!(effort(&r, "src/main/deep/b.fk"), 0);
    let m = &r.measures;
    assert_eq!(m.total.effort_minutes.total, 55);
    assert_eq!(
        m.total.effort_minutes.medium, 45,
        "cognitive 30 + LOUD 3 × 5"
    );
    assert_eq!(m.total.effort_minutes.low, 10);
    assert_eq!(m.total.effort_minutes.maintainability, 55);
    assert_eq!((m.main.files, m.test.files), (3, 1));
    assert_eq!(
        (m.main.effort_minutes.total, m.test.effort_minutes.total),
        (50, 5)
    );
    assert_eq!(m.main.findings + m.test.findings, m.total.findings);
    assert_eq!(m.languages["fk"].effort_minutes, m.total.effort_minutes);
    let dirs: Vec<(&str, u64, u64)> = m
        .directories
        .iter()
        .map(|d| (d.path.as_str(), d.files, d.effort_minutes))
        .collect();
    assert_eq!(
        dirs,
        [("src", 3, 50), ("src/main", 2, 45), ("src/test", 1, 5)],
        "depth 2 by default; root files only in the total"
    );
    assert_eq!(m.directories_omitted, 0);
    assert_eq!(r.format_version, 1);

    // A lower limit for the file raises the estimate; depth 1 keeps the top level only.
    let yaml =
        "rules:\n  fk/cognitive-complexity: { params: { threshold: 9 } }\nmetrics: { depth: 1 }\n";
    let (s, _) = scanner(root, yaml);
    let r = s.scan(&opts(SourceSpec::Directory, None)).unwrap();
    assert_eq!(effort(&r, "src/main/a.fk"), 50 + 5 + 10);
    let dirs: Vec<&str> = r
        .measures
        .directories
        .iter()
        .map(|d| d.path.as_str())
        .collect();
    assert_eq!(dirs, ["src"]);
}

#[test]
fn output_is_deterministic_across_thread_counts() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    for i in 0..40 {
        write(
            root,
            &format!("m{}/f{i}.fk", i % 5),
            &format!("fn f{i} cog={}\nLOUD\nend\n{}", 10 + i, dup_body("d", 12)),
        );
    }
    let (s, _) = scanner(root, "");
    let run = |threads| {
        let r = s
            .scan(&ScanOptions {
                threads: Some(threads),
                ..opts(SourceSpec::Directory, None)
            })
            .unwrap();
        let v = serde_json::json!({
            "findings": r.findings, "files": r.files, "dups": r.duplications,
            "measures": r.measures, "gate": r.gate, "rules": r.rules,
        });
        serde_json::to_string(&v).unwrap()
    };
    let one = run(1);
    assert_eq!(one, run(4));
    assert_eq!(one, run(12));
}

#[test]
fn worktree_uses_index_blob_ids_and_cache() {
    let dir = tempfile::tempdir().unwrap();
    let cache = tempfile::tempdir().unwrap();
    let root = dir.path();
    init_repo(root);
    write(root, "a.fk", "LOUD\n");
    write(root, "b.fk", "x;\n");
    write(root, "gone.fk", "LOUD\n");
    commit_all(root, "init");
    let (s, calls) = scanner(root, "");
    let o = opts(SourceSpec::Auto, Some(cache.path()));

    let r1 = s.scan(&o).unwrap();
    assert_eq!(r1.source.kind, "worktree");
    assert_eq!(r1.stats.files_analyzed, 3);
    assert_eq!(calls.load(Ordering::SeqCst), 3);

    let r2 = s.scan(&o).unwrap();
    assert_eq!(r2.stats.cache_hits, 3);
    assert_eq!(
        calls.load(Ordering::SeqCst),
        3,
        "warm scan never calls the plugin"
    );
    assert_eq!(
        serde_json::to_string(&r1.findings).unwrap(),
        serde_json::to_string(&r2.findings).unwrap()
    );

    // dirty tracked file, untracked file, deleted tracked file
    write(root, "b.fk", "x;\nLOUD\n");
    write(root, "new.fk", "LOUD\n");
    std::fs::remove_file(root.join("gone.fk")).unwrap();
    let r3 = s.scan(&o).unwrap();
    assert_eq!(status_of(&r3, "a.fk"), FileStatus::Cached);
    assert_eq!(status_of(&r3, "b.fk"), FileStatus::Analyzed);
    assert_eq!(status_of(&r3, "new.fk"), FileStatus::Analyzed);
    assert!(r3.files.iter().all(|f| f.path != "gone.fk"));
    assert_eq!(find(&r3, "b.fk", "fk/loud").len(), 1);

    // a config change invalidates through the rule-set hash (close the first scanner's cache)
    drop(s);
    let (s2, calls2) = scanner(root, "rules: { fk/loud: HIGH }");
    let r4 = s2.scan(&o).unwrap();
    assert_eq!(r4.stats.cache_hits, 0);
    assert_eq!(calls2.load(Ordering::SeqCst), 3);
    assert_eq!(find(&r4, "a.fk", "fk/loud")[0].severity, Severity::High);
    assert!(r4.stats.cache_enabled);
    drop(s2);
}

#[test]
fn cache_disabled_and_lock_contention_degrade_gracefully() {
    let dir = tempfile::tempdir().unwrap();
    let cache = tempfile::tempdir().unwrap();
    write(dir.path(), "a.fk", "LOUD\n");
    let (s1, _) = scanner(dir.path(), "");
    let (s2, _) = scanner(dir.path(), "");
    let o = opts(SourceSpec::Directory, Some(cache.path()));
    let r1 = s1.scan(&o).unwrap();
    assert!(r1.stats.cache_enabled);
    // s1 keeps the cache open, so s2 runs without it and says so
    let r2 = s2.scan(&o).unwrap();
    assert!(!r2.stats.cache_enabled);
    assert!(
        r2.diagnostics.iter().any(|d| d.message.contains("in use")),
        "{:?}",
        r2.diagnostics
    );
    assert_eq!(r2.findings.len(), 1);
    s1.close_cache();
    let r3 = s2.scan(&o).unwrap();
    assert!(r3.stats.cache_enabled);
    assert_eq!(r3.stats.cache_hits, 1);
    drop(s1);
    drop(s2);
}

#[test]
fn rev_and_staged_sources_read_the_object_database() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    init_repo(root);
    write(root, "a.fk", "LOUD\n");
    commit_all(root, "v1");
    write(root, "a.fk", "x;\nHIGHBUG\n");
    write(root, "b.fk", "MAGIC\n");
    commit_all(root, "v2");
    write(root, "a.fk", "staged;\nstaged;\nLOUD\n");
    git(root, &["add", "a.fk"]);
    write(root, "a.fk", "worktree only\n");

    let (s, _) = scanner(root, "");
    let v1 = s
        .scan(&opts(SourceSpec::Rev("HEAD~1".into()), None))
        .unwrap();
    assert_eq!(ids(&v1), vec![("a.fk".into(), 1, "fk/loud".into())]);
    assert_eq!(v1.source.kind, "rev");
    assert_eq!(v1.source.commit.as_deref().map(str::len), Some(40));

    let staged = s.scan(&opts(SourceSpec::Staged, None)).unwrap();
    assert_eq!(
        ids(&staged),
        vec![
            ("a.fk".into(), 3, "fk/loud".into()),
            ("b.fk".into(), 1, "fk/magic".into())
        ]
    );

    let wt = s.scan(&opts(SourceSpec::Worktree, None)).unwrap();
    assert_eq!(ids(&wt), vec![("b.fk".into(), 1, "fk/magic".into())]);

    assert!(s
        .scan(&opts(SourceSpec::Rev("no-such-branch".into()), None))
        .is_err());
}

#[test]
fn new_code_classification_with_rename_and_untracked() {
    let dir = tempfile::tempdir().unwrap();
    let cache = tempfile::tempdir().unwrap();
    let root = dir.path();
    init_repo(root);
    write(root, "a.fk", "x;\nfn work cog=18\n  LOUD\n  MAGIC\nend\n");
    let b_body = "one;\ntwo;\nLOUD\nthree;\nfour;\nfive;\nsix;\nseven;\n";
    write(root, "old/b.fk", b_body);
    write(root, "c.fk", "LOUD\n");
    commit_all(root, "base");
    git(root, &["checkout", "-q", "-b", "feature"]);
    // a.fk: shift lines, worsen complexity, add a HIGH bug, fix MAGIC; the old LOUD stays on an
    // unchanged line of this changed file.
    write(
        root,
        "a.fk",
        "added;\nadded;\nx;\nfn work cog=25\n  LOUD\n  HIGHBUG\nend\n",
    );
    // b.fk renamed with a small edit: its LOUD is unchanged, the new INCUB is new
    std::fs::create_dir_all(root.join("new")).unwrap();
    git(root, &["mv", "old/b.fk", "new/b.fk"]);
    write(root, "new/b.fk", &format!("{b_body}INCUB\n"));
    commit_all(root, "feature");
    write(root, "d.fk", "LOUD\n"); // untracked

    let (s, _) = scanner(root, "gate: { worsened: fail }");
    let o = ScanOptions {
        base: Some("main".into()),
        ..opts(SourceSpec::Worktree, Some(cache.path()))
    };
    let r = s.scan(&o).unwrap();
    let st = |path: &str, rule: &str| {
        find(&r, path, rule)
            .iter()
            .map(|f| f.status)
            .collect::<Vec<_>>()
    };
    assert_eq!(st("a.fk", "fk/loud"), vec![FindingStatus::Unchanged]);
    assert_eq!(st("a.fk", "fk/high-bug"), vec![FindingStatus::New]);
    assert_eq!(
        st("a.fk", "fk/cognitive-complexity"),
        vec![FindingStatus::Worsened]
    );
    assert_eq!(st("new/b.fk", "fk/loud"), vec![FindingStatus::Unchanged]);
    assert_eq!(st("new/b.fk", "fk/incubating"), vec![FindingStatus::New]);
    assert_eq!(st("c.fk", "fk/loud"), vec![FindingStatus::Unchanged]);
    assert_eq!(st("d.fk", "fk/loud"), vec![FindingStatus::New]);

    let nc = r.new_code.as_ref().unwrap();
    assert_eq!(nc.merge_base, git(root, &["rev-parse", "main"]));
    assert_eq!(
        nc.renamed.get("new/b.fk").map(String::as_str),
        Some("old/b.fk")
    );
    assert_eq!(nc.new_lines["a.fk"], vec![(1, 2), (4, 4), (6, 6)]);
    assert_eq!(nc.new_lines["new/b.fk"], vec![(9, 9)]);
    assert_eq!(nc.new_lines["d.fk"], vec![(1, 1)]);
    assert!(!nc.new_lines.contains_key("c.fk"));
    assert_eq!(nc.measures.fixed_findings.low, 1, "MAGIC disappeared");
    assert_eq!(
        nc.measures.new_findings.high, 2,
        "HIGHBUG + incubating (reported, not gating)"
    );
    assert_eq!(nc.measures.worsened_findings.medium, 1);
    assert_eq!(nc.measures.changed_files, 3);
    // New-code effort: the new HIGHBUG and d.fk's LOUD (5 minutes each); the incubating finding
    // and the worsened (not new) complexity don't count.
    assert_eq!(nc.measures.new_effort_minutes.total, 10);
    assert_eq!(nc.measures.new_effort_minutes.high, 5);

    let names: Vec<(&str, bool)> = r
        .gate
        .conditions
        .iter()
        .map(|c| (c.name.as_str(), c.passed))
        .collect();
    assert_eq!(
        names,
        vec![
            ("new_findings", false),
            ("new_duplication_pct", true),
            ("new_coverage_pct", true),
            ("worsened", false)
        ]
    );
    let nf = &r.gate.conditions[0];
    assert_eq!(
        nf.actual,
        Some(1.0),
        "the incubating HIGH finding does not gate"
    );
    assert!(!r.gate.passed);

    // warm rerun: base blobs come from the cache too
    let r2 = s.scan(&o).unwrap();
    assert_eq!(r2.stats.files_analyzed, 0);
    assert_eq!(r2.stats.base_files_analyzed, 0);
    assert!(r2.stats.base_cache_hits >= 2);
    assert_eq!(
        serde_json::to_string(&r.findings).unwrap(),
        serde_json::to_string(&r2.findings).unwrap()
    );

    // changed_only limits the scan to changed files
    let co = s
        .scan(&ScanOptions {
            changed_only: true,
            ..o.clone()
        })
        .unwrap();
    let paths: Vec<&str> = co.files.iter().map(|f| f.path.as_str()).collect();
    assert_eq!(paths, vec!["a.fk", "d.fk", "new/b.fk"]);

    // rev head: compare the feature commit with main
    let rv = s
        .scan(&ScanOptions {
            base: Some("main".into()),
            ..opts(SourceSpec::Rev("feature".into()), None)
        })
        .unwrap();
    assert_eq!(
        find(&rv, "a.fk", "fk/high-bug")[0].status,
        FindingStatus::New
    );
    assert!(rv.files.iter().all(|f| f.path != "d.fk"));
    drop(s);
}

#[test]
fn duplication_findings_measures_and_new_duplication() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    init_repo(root);
    write(
        root,
        "a.fk",
        &format!("class A {{\n{}}}\n", dup_body("a", 15)),
    );
    write(root, "pad.fk", &"x;\n".repeat(30));
    commit_all(root, "base");
    git(root, &["checkout", "-q", "-b", "feature"]);
    write(
        root,
        "b.fk",
        &format!(
            "// copy 1\n// copy 2\n// copy 3\nclass B {{\n{}}}\n",
            dup_body("a", 15)
        ),
    );
    commit_all(root, "copy");

    let (s, _) = scanner(root, "");
    let r = s
        .scan(&ScanOptions {
            base: Some("main".into()),
            ..opts(SourceSpec::Worktree, None)
        })
        .unwrap();
    assert_eq!(r.duplications.len(), 1);
    let block = &r.duplications[0];
    let occ: Vec<(&str, u32, u32)> = block
        .occurrences
        .iter()
        .map(|o| (o.path.as_str(), o.start_line, o.end_line))
        .collect();
    assert_eq!(occ, vec![("a.fk", 1, 17), ("b.fk", 4, 20)]);
    let da = find(&r, "a.fk", "fk/duplicated-block");
    let db = find(&r, "b.fk", "fk/duplicated-block");
    assert_eq!(da.len(), 1);
    assert_eq!(da[0].secondary[0].path, "b.fk");
    assert_eq!(
        da[0].status,
        FindingStatus::Unchanged,
        "a.fk did not change"
    );
    assert_eq!(db[0].status, FindingStatus::New);
    assert_eq!(
        da[0].fingerprint, db[0].fingerprint,
        "anchored on the duplicated content"
    );
    let fa = r.files.iter().find(|f| f.path == "a.fk").unwrap();
    assert_eq!(fa.measures.as_ref().unwrap().duplicated_lines, 17);
    assert_eq!(r.measures.total.duplicated_lines, 34);
    assert_eq!(r.measures.total.duplicated_files, 2);
    let nc = &r.new_code.as_ref().unwrap().measures;
    assert_eq!(nc.new_lines, 20);
    assert_eq!(nc.new_duplicated_lines, 17);
    let dup_cond = r
        .gate
        .conditions
        .iter()
        .find(|c| c.name == "new_duplication_pct")
        .unwrap();
    assert!(!dup_cond.passed);
}

#[test]
fn suppressions_end_to_end() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    let text = format!(
        "// mote-ignore-file[duplicated-block]: generated fixtures\nLOUD // mote-ignore[loud]: demo output\nx; // mote-ignore[magic]: nothing here\n// mote-ignore\nHIGHBUG\n@Suppress(loud)\nLOUD\n@SuppressCompat\nLOUD\nMAGIC // NOSONAR\nclass C {{\n{}}}\n",
        dup_body("s", 15)
    );
    write(root, "a.fk", &text);
    write(
        root,
        "b.fk",
        &format!("class D {{\n{}}}\n", dup_body("s", 15)),
    );
    let (s, _) = scanner(root, "");
    let r = s.scan(&opts(SourceSpec::Directory, None)).unwrap();
    let got: Vec<(u32, &str, Option<&str>)> = r
        .findings
        .iter()
        .filter(|f| f.path == "a.fk")
        .map(|f| {
            (
                f.range.start_line,
                f.rule_id.as_str(),
                f.suppressed.as_ref().map(|x| x.kind.as_str()),
            )
        })
        .collect();
    assert_eq!(
        got,
        vec![
            (2, "fk/loud", Some("mote-ignore")),
            (3, "mote/unused-suppression", None),
            (4, "mote/blanket-suppression", None),
            (4, "mote/suppression-without-reason", None),
            (5, "fk/high-bug", Some("mote-ignore")),
            (7, "fk/loud", Some("annotation")),
            (9, "fk/loud", None),
            (10, "fk/magic", None),
            (11, "fk/duplicated-block", Some("mote-ignore-file")),
        ]
    );
    // suppressed findings never gate
    assert!(r.gate.passed);

    // compat mode: NOSONAR and compat-scoped suppressions apply, NOSONAR is reported as blanket
    let (s, _) = scanner(root, "suppressions: { compat: true }");
    let r = s.scan(&opts(SourceSpec::Directory, None)).unwrap();
    let a: Vec<(u32, &str, bool)> = r
        .findings
        .iter()
        .filter(|f| f.path == "a.fk" && (8..=10).contains(&f.range.start_line))
        .map(|f| {
            (
                f.range.start_line,
                f.rule_id.as_str(),
                f.suppressed.is_some(),
            )
        })
        .collect();
    assert_eq!(
        a,
        vec![
            (9, "fk/loud", true),
            (10, "fk/magic", true),
            (10, "mote/blanket-suppression", false)
        ]
    );

    // A list selects sources one by one: the fake plugin's compat suppression is a `pmd` one.
    for (yaml, want) in [
        (
            "suppressions: { compat: [nosonar] }",
            vec![
                (9, "fk/loud", None),
                (10, "fk/magic", Some("nosonar")),
                (10, "mote/blanket-suppression", None),
            ],
        ),
        (
            "suppressions: { compat: [pmd, spotbugs] }",
            vec![(9, "fk/loud", Some("compat")), (10, "fk/magic", None)],
        ),
        (
            "suppressions: { compat: false }",
            vec![(9, "fk/loud", None), (10, "fk/magic", None)],
        ),
    ] {
        let (s, _) = scanner(root, yaml);
        let r = s.scan(&opts(SourceSpec::Directory, None)).unwrap();
        let got: Vec<(u32, &str, Option<&str>)> = r
            .findings
            .iter()
            .filter(|f| f.path == "a.fk" && (8..=10).contains(&f.range.start_line))
            .map(|f| {
                (
                    f.range.start_line,
                    f.rule_id.as_str(),
                    f.suppressed.as_ref().map(|x| x.kind.as_str()),
                )
            })
            .collect();
        assert_eq!(got, want, "{yaml}");
        // `mote-ignore` comments are still checked for being unused, whatever the sources.
        assert!(
            r.findings.iter().any(|f| f.path == "a.fk"
                && f.range.start_line == 3
                && f.rule_id == "mote/unused-suppression"),
            "{yaml}"
        );
    }
}

