/// A scanner whose fake plugin has the id `java` (files `*.java`).
fn java_scanner(root: &std::path::Path, yaml: &str) -> mote_engine::Scanner {
    let reg =
        mote_engine::Registry::new(vec![Box::new(common::fake_plugin::FakePlugin::new("java"))])
            .expect("registry");
    let config = mote_engine::Config::from_yaml_str(yaml).expect("config");
    mote_engine::Scanner::new(std::sync::Arc::new(reg), config, root).expect("scanner")
}

/// `path` → the release the plugin saw (`SHOW_RELEASE` findings).
fn releases_seen(r: &ScanResult) -> Vec<(String, String)> {
    r.findings
        .iter()
        .filter(|f| f.message.starts_with("release "))
        .map(|f| (f.path.clone(), f.message["release ".len()..].to_string()))
        .collect()
}

fn pom_release(release: &str) -> String {
    format!(
        "<project><modelVersion>4.0.0</modelVersion><properties>\
         <maven.compiler.release>{release}</maven.compiler.release></properties></project>\n"
    )
}

#[test]
fn java_release_from_build_files_reaches_the_plugin_and_the_cache_key() {
    let dir = tempfile::tempdir().unwrap();
    let cache = tempfile::tempdir().unwrap();
    let root = dir.path();
    write(root, "pom.xml", &pom_release("11"));
    write(root, "A.java", "SHOW_RELEASE\n");
    write(root, "svc/pom.xml", &pom_release("17"));
    write(root, "svc/src/main/java/B.java", "SHOW_RELEASE\n");
    write(root, "tool/build.gradle", "sourceCompatibility = '1.8'\n");
    write(root, "tool/C.java", "SHOW_RELEASE\n");
    write(root, "tool/sub/D.java", "SHOW_RELEASE\n");
    let o = opts(SourceSpec::Directory, Some(cache.path()));
    let s = java_scanner(root, "");
    let r = s.scan(&o).unwrap();
    assert_eq!(
        releases_seen(&r),
        vec![
            ("A.java".into(), "11".into()),
            ("svc/src/main/java/B.java".into(), "17".into()),
            ("tool/C.java".into(), "8".into()),
            ("tool/sub/D.java".into(), "8".into()),
        ]
    );
    let warm = s.scan(&o).unwrap();
    assert_eq!(warm.stats.cache_hits, 4);

    // A changed build file invalidates the files it covers, and only those.
    write(root, "svc/pom.xml", &pom_release("21"));
    let r = s.scan(&o).unwrap();
    assert_eq!(status_of(&r, "A.java"), FileStatus::Cached);
    assert_eq!(
        status_of(&r, "svc/src/main/java/B.java"),
        FileStatus::Analyzed
    );
    assert_eq!(releases_seen(&r)[1].1, "21");

    // `config explain` sees the same.
    let e = s.effective_rules("svc/src/main/java/B.java").unwrap();
    let jr = e.java_release.expect("release");
    assert_eq!(jr.release, 21);
    assert_eq!(jr.origin.to_string(), "svc/pom.xml: maven.compiler.release");
    assert!(e
        .rules
        .values()
        .all(|r| !r.params.contains_key(mote_engine::JAVA_RELEASE_PARAM)));
    drop(s);

    // The configuration overrides every build file.
    let s = java_scanner(root, "java: { release: 25 }");
    let r = s.scan(&o).unwrap();
    assert!(releases_seen(&r).iter().all(|(_, v)| v == "25"));
    assert_eq!(
        s.effective_rules("tool/C.java")
            .unwrap()
            .java_release
            .unwrap()
            .origin,
        mote_engine::ReleaseOrigin::Config
    );
    drop(s);

    // No build file: unknown, and the parameter is absent.
    let bare = tempfile::tempdir().unwrap();
    write(bare.path(), "E.java", "SHOW_RELEASE\n");
    let s = java_scanner(bare.path(), "");
    let r = s.scan(&opts(SourceSpec::Directory, None)).unwrap();
    assert_eq!(releases_seen(&r), vec![("E.java".into(), "none".into())]);
    assert!(s.effective_rules("E.java").unwrap().java_release.is_none());
}

#[test]
fn java_release_of_a_revision_comes_from_its_build_files() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    init_repo(root);
    write(root, "pom.xml", &pom_release("11"));
    write(root, "src/A.java", "SHOW_RELEASE\n");
    commit_all(root, "v1");
    write(root, "pom.xml", &pom_release("17"));
    let s = java_scanner(root, "");
    let head = s.scan(&opts(SourceSpec::Rev("HEAD".into()), None)).unwrap();
    assert_eq!(
        releases_seen(&head),
        vec![("src/A.java".into(), "11".into())]
    );
    let wt = s.scan(&opts(SourceSpec::Worktree, None)).unwrap();
    assert_eq!(releases_seen(&wt), vec![("src/A.java".into(), "17".into())]);
    // `changed_only` narrows the analyzed files, not the build files that apply to them.
    write(root, "src/A.java", "x;\nSHOW_RELEASE\n");
    let changed = s
        .scan(&ScanOptions {
            base: Some("HEAD".into()),
            changed_only: true,
            ..opts(SourceSpec::Worktree, None)
        })
        .unwrap();
    assert_eq!(
        releases_seen(&changed),
        vec![("src/A.java".into(), "17".into())]
    );
}

#[test]
fn remote_clone_from_local_url_and_config_at_rev() {
    let origin = tempfile::tempdir().unwrap();
    let cache = tempfile::tempdir().unwrap();
    init_repo(origin.path());
    write(origin.path(), "a.fk", "LOUD\n");
    write(origin.path(), ".mote.yaml", "rules: { fk/loud: HIGH }\n");
    let head = commit_all(origin.path(), "init");
    let url = format!(
        "file://{}",
        origin.path().to_string_lossy().replace('\\', "/")
    );
    let checkout = clone_remote(&url, None, cache.path()).unwrap();
    assert_eq!(checkout.commit, head);
    let (config, from) = discover_config(&checkout.dir, Some(&checkout.commit)).unwrap();
    assert!(from.unwrap().ends_with(".mote.yaml"));
    let (reg, _) = common::registry();
    let s = mote_engine::scan::Scanner::new(reg, config, &checkout.dir).unwrap();
    let r = s
        .scan(&opts(SourceSpec::Rev(checkout.commit.clone()), None))
        .unwrap();
    assert_eq!(r.findings.len(), 1);
    assert_eq!(r.findings[0].severity, Severity::High);
    // a second clone of the same URL refreshes the existing directory
    let again = clone_remote(&url, None, cache.path()).unwrap();
    assert_eq!(again.dir, checkout.dir);
    assert_eq!(again.commit, head);
}

