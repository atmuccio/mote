struct RuleRow {
    id: String,
    severity: String,
    default_enabled: bool,
    status: String,
}

fn rule_catalog() -> Vec<RuleRow> {
    let run = mote(&workspace_root(), &["rules", "--all", "--format", "json"]);
    assert_eq!(run.code, 0, "{run:?}");
    let v: Value = serde_json::from_str(&run.stdout).expect("rules JSON");
    let list = v
        .as_array()
        .or_else(|| v["rules"].as_array())
        .expect("rules array");
    list.iter()
        .map(|r| RuleRow {
            id: r["id"].as_str().unwrap_or_default().to_string(),
            severity: r["severity"].as_str().unwrap_or_default().to_string(),
            default_enabled: r["default_enabled"].as_bool().unwrap_or(false),
            status: r["status"].as_str().unwrap_or_default().to_string(),
        })
        // The test binary also carries the `.tl` test plugin; it isn't part of the product.
        .filter(|r| {
            r.id.starts_with("mote/") || SAMPLE_LANGUAGES.iter().any(|l| r.id.starts_with(l.2))
        })
        .collect()
}

/// Findings per rule id and sample, from one JSONL snapshot per sample.
fn findings_by_rule(
    snapshots: &[(&'static str, String)],
) -> BTreeMap<String, BTreeMap<&'static str, usize>> {
    let mut map: BTreeMap<String, BTreeMap<&'static str, usize>> = BTreeMap::new();
    for (name, text) in snapshots {
        for line in text.lines().filter(|l| !l.trim().is_empty()) {
            let v: Value = serde_json::from_str(line).expect("golden JSONL");
            let rule = v["rule"].as_str().unwrap_or_default().to_string();
            *map.entry(rule).or_default().entry(*name).or_default() += 1;
        }
    }
    map
}

fn coverage_markdown(snapshots: &[(&'static str, String)]) -> String {
    let catalog = rule_catalog();
    let fired = findings_by_rule(snapshots);
    let mut groups: Vec<(&str, String, Vec<&RuleRow>)> = SAMPLE_LANGUAGES
        .iter()
        .map(|(_, title, prefix)| {
            let rows = catalog
                .iter()
                .filter(|r| r.id.starts_with(prefix))
                .collect();
            (*prefix, title.to_string(), rows)
        })
        .collect();
    groups.push((
        "mote/",
        "Engine (meta rules)".to_string(),
        catalog
            .iter()
            .filter(|r| r.id.starts_with("mote/"))
            .collect(),
    ));

    let mut summary = String::new();
    let mut tables = String::new();
    let (mut all_hit, mut all_total) = (0, 0);
    for (_, title, rows) in &groups {
        let hit = rows.iter().filter(|r| fired.contains_key(&r.id)).count();
        all_hit += hit;
        all_total += rows.len();
        summary.push_str(&format!(
            "| {title} | {hit} | {} | {} |\n",
            rows.len(),
            rows.len() - hit
        ));
        let missing: Vec<String> = rows
            .iter()
            .filter(|r| !fired.contains_key(&r.id))
            .map(|r| format!("`{}`", r.id))
            .collect();
        tables.push_str(&format!(
            "\n<details>\n<summary>{title}: {hit} of {} rules exercised</summary>\n\n",
            rows.len()
        ));
        if !missing.is_empty() {
            tables.push_str(&format!("Not exercised: {}.\n\n", missing.join(", ")));
        }
        tables.push_str(
            "| Rule | Severity | Default | Findings in the samples |\n|---|---|---|---|\n",
        );
        for r in rows {
            let default = match (r.default_enabled, r.status.as_str()) {
                (_, "deprecated") => "deprecated",
                (true, "incubating") => "on (incubating)",
                (true, _) => "on",
                (false, _) => "off",
            };
            let hits = match fired.get(&r.id) {
                None => "—".to_string(),
                Some(per) => per
                    .iter()
                    .map(|(sample, n)| format!("{n} ({sample})"))
                    .collect::<Vec<_>>()
                    .join(", "),
            };
            tables.push_str(&format!(
                "| `{}` | {} | {default} | {hits} |\n",
                r.id, r.severity
            ));
        }
        tables.push_str("\n</details>\n");
    }
    let unknown: Vec<&String> = fired
        .keys()
        .filter(|id| !catalog.iter().any(|r| &r.id == *id))
        .collect();
    assert!(
        unknown.is_empty(),
        "goldens mention rules missing from the catalog: {unknown:?}"
    );

    let mut totals =
        String::from("| Sample | Findings | HIGH | MEDIUM | LOW |\n|---|--:|--:|--:|--:|\n");
    for (name, text) in snapshots {
        let mut by_severity: BTreeMap<String, usize> = BTreeMap::new();
        let mut total = 0;
        for line in text.lines().filter(|l| !l.trim().is_empty()) {
            let v: Value = serde_json::from_str(line).expect("golden JSONL");
            *by_severity
                .entry(v["severity"].as_str().unwrap_or_default().to_string())
                .or_default() += 1;
            total += 1;
        }
        let n = |s: &str| by_severity.get(s).copied().unwrap_or(0);
        totals.push_str(&format!(
            "| `bench/samples/{name}` | {total} | {} | {} | {} |\n",
            n("HIGH"),
            n("MEDIUM"),
            n("LOW")
        ));
    }

    format!(
        "{COVERAGE_BEGIN}\n\n{totals}\n| Rules | Exercised | Total | Not exercised |\n|---|---|---|---|\n\
         {summary}| **All** | **{all_hit}** | **{all_total}** | **{}** |\n{tables}\n{COVERAGE_END}",
        all_total - all_hit
    )
}

#[test]
fn coverage_table_in_docs_is_current() {
    let doc_path = workspace_root().join("docs").join("benchmark.md");
    let doc = normalize(
        &std::fs::read_to_string(&doc_path)
            .unwrap_or_else(|e| panic!("read {}: {e}", doc_path.display())),
    );
    let (Some(begin), Some(end)) = (doc.find(COVERAGE_BEGIN), doc.find(COVERAGE_END)) else {
        panic!("docs/benchmark.md lacks the coverage markers:\n{COVERAGE_BEGIN}\n{COVERAGE_END}");
    };
    assert!(
        begin < end,
        "coverage markers out of order in docs/benchmark.md"
    );
    let current = &doc[begin..end + COVERAGE_END.len()];
    // When blessing, the golden tests rewrite the snapshots concurrently: derive the table from
    // fresh scans instead of reading files that may be half-written (or not exist yet).
    let snapshots: Vec<(&'static str, String)> = SAMPLES
        .iter()
        .map(|name| {
            let text = if blessing() {
                scan_sample(name, &[])
            } else {
                read_golden(name)
            };
            (*name, text)
        })
        .collect();
    let wanted = coverage_markdown(&snapshots);
    if blessing() {
        let updated = format!(
            "{}{wanted}{}",
            &doc[..begin],
            &doc[end + COVERAGE_END.len()..]
        );
        std::fs::write(&doc_path, updated).unwrap();
        return;
    }
    assert!(
        current == wanted,
        "the coverage table in docs/benchmark.md is out of date; regenerate it with\n  \
         MOTE_BLESS=1 cargo test -p mote-cli --test samples\n\nexpected:\n{wanted}"
    );
}
