//! Accuracy benchmark, part 2: the bad-code sample projects.
//!
//! Each project in `bench/samples/<name>/` is scanned with its own `.mote.yaml` and the JSONL
//! findings are compared with the golden snapshot `bench/expected/<name>.jsonl`. The coverage
//! table in `docs/benchmark.md` (between the `coverage:begin`/`coverage:end` markers) is derived
//! from the goldens and the rule catalog and checked too.
//!
//! After an intended change, rewrite the goldens and the table, then review the diff by hand:
//!
//! ```text
//! MOTE_BLESS=1 cargo test -p mote-cli --test samples
//! git diff bench/expected docs/benchmark.md
//! ```
//!
//! The sample is copied to a temporary directory with LF line endings before it is scanned, so
//! the result doesn't depend on `core.autocrlf` or on the enclosing repository. Paths in the
//! output are relative to the sample root, exactly as `mote scan bench/samples/<name>
//! --format jsonl --no-cache` prints them.

mod common;

use common::*;
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

const SAMPLES: &[&str] = &["java", "ts"];

/// Rule-id prefixes covered by each sample (`mote/*` meta rules count for every sample).
const SAMPLE_LANGUAGES: &[(&str, &str, &str)] = &[
    ("java", "Java", "java/"),
    ("ts", "JavaScript / TypeScript", "js/"),
];

const COVERAGE_BEGIN: &str = "<!-- coverage:begin (generated by crates/mote-cli/tests/samples.rs; bless with MOTE_BLESS=1) -->";
const COVERAGE_END: &str = "<!-- coverage:end -->";

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join("..")
}

fn blessing() -> bool {
    std::env::var_os("MOTE_BLESS").is_some_and(|v| v != "0" && !v.is_empty())
}

fn normalize(text: &str) -> String {
    text.replace("\r\n", "\n")
}

/// Copy `src` into `dst`, converting CRLF to LF in every file.
fn copy_tree_lf(src: &Path, dst: &Path) {
    std::fs::create_dir_all(dst).unwrap();
    let mut entries: Vec<_> = std::fs::read_dir(src)
        .unwrap_or_else(|e| panic!("read {}: {e}", src.display()))
        .map(|e| e.unwrap())
        .collect();
    entries.sort_by_key(|e| e.file_name());
    for entry in entries {
        let name = entry.file_name();
        if name == ".mote" || name == "node_modules" {
            continue; // a local cache or install, not part of the sample
        }
        let from = entry.path();
        let to = dst.join(&name);
        if entry.file_type().unwrap().is_dir() {
            copy_tree_lf(&from, &to);
        } else {
            let bytes = std::fs::read(&from).unwrap();
            let text = String::from_utf8(bytes)
                .unwrap_or_else(|_| panic!("{} is not UTF-8", from.display()));
            std::fs::write(&to, normalize(&text)).unwrap();
        }
    }
}

/// Scan a copy of `bench/samples/<name>` and return the JSONL output.
fn scan_sample(name: &str, extra: &[&str]) -> String {
    let src = workspace_root().join("bench").join("samples").join(name);
    assert!(src.is_dir(), "missing sample project {}", src.display());
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join(name);
    copy_tree_lf(&src, &root);
    let mut args = vec!["scan", ".", "--format", "jsonl", "--no-cache", "--no-gate"];
    args.extend_from_slice(extra);
    let run = mote(&root, &args);
    assert_eq!(run.code, 0, "scan of sample `{name}` failed: {run:?}");
    normalize(&run.stdout)
}

fn golden_path(name: &str) -> PathBuf {
    workspace_root()
        .join("bench")
        .join("expected")
        .join(format!("{name}.jsonl"))
}

fn read_golden(name: &str) -> String {
    let path = golden_path(name);
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "read {}: {e}\nCreate it with: MOTE_BLESS=1 cargo test -p mote-cli --test samples",
            path.display()
        )
    });
    normalize(&text)
}

/// A readable account of how two JSONL snapshots differ (both are sorted, one finding per line).
fn describe_diff(expected: &str, actual: &str) -> String {
    let exp: BTreeSet<&str> = expected.lines().collect();
    let act: BTreeSet<&str> = actual.lines().collect();
    let mut out = String::new();
    for line in expected.lines().filter(|l| !act.contains(l)) {
        out.push_str(&format!("- {line}\n"));
    }
    for line in actual.lines().filter(|l| !exp.contains(l)) {
        out.push_str(&format!("+ {line}\n"));
    }
    if out.is_empty() {
        out.push_str("(same findings in a different order or with different whitespace)\n");
    }
    out
}

fn check_sample(name: &str) {
    let actual = scan_sample(name, &[]);
    for line in actual.lines() {
        let v: Value = serde_json::from_str(line)
            .unwrap_or_else(|e| panic!("invalid JSONL line ({e}): {line}"));
        let rule = v["rule"].as_str().unwrap_or_default();
        assert!(
            rule != "mote/parse-error" && rule != "mote/internal-error",
            "sample `{name}` must parse and analyze cleanly: {line}"
        );
    }
    if blessing() {
        let path = golden_path(name);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &actual).unwrap();
        return;
    }
    let expected = read_golden(name);
    assert!(
        expected == actual,
        "findings for bench/samples/{name} differ from bench/expected/{name}.jsonl \
         (- expected, + actual):\n{}\nIf the change is intended, bless it and review the diff:\n  \
         MOTE_BLESS=1 cargo test -p mote-cli --test samples",
        describe_diff(&expected, &actual)
    );
}

#[test]
fn java_sample_matches_golden() {
    check_sample("java");
}

#[test]
fn ts_sample_matches_golden() {
    check_sample("ts");
}

#[test]
fn sample_output_does_not_depend_on_thread_count() {
    for name in SAMPLES {
        assert_eq!(
            scan_sample(name, &["--threads", "1"]),
            scan_sample(name, &["--threads", "4"]),
            "sample `{name}`"
        );
    }
}

