//! `java/useless-override` — an override whose body only calls the same super method with
//! the same arguments.

use super::util;
use crate::prelude::*;

pub static META: RuleMeta = RuleMeta {
    kind: RuleKind::CodeSmell,
    quality: Quality::Maintainability,
    severity: Severity::Low,
    status: RuleStatus::Stable,
    tags: &["redundant", "inheritance"],
    remediation_minutes: 2,
    description: r#"Detects an `@Override` method whose whole body is `super.sameMethod(..)` (or
`return super.sameMethod(..)`) called with its own parameters, in the same order.

**Why it matters.** Such a method does exactly what the inherited one does: it adds lines to
read and keep in sync (a new parameter in the parent must be threaded through), and it
misleads readers into looking for a difference that is not there. It is often the leftover of
an override whose extra behavior was removed, or generated by an IDE and never filled in.

**How to fix.** Remove the method.

```java
// Noncompliant
@Override
public void start(Context context) {
    super.start(context);
}

// Compliant: no override at all, or one that adds behavior
@Override
public void start(Context context) {
    super.start(context);
    registerListeners();
}
```

Not reported: overrides that change something besides the body — another annotation
(`@Transactional`, `@Deprecated`, …), annotated parameters, `final` or `synchronized`, or a
visibility wider than the parent's. Since a `public` override of a `protected` method is a
deliberate way to expose it, `public` overrides are only reported when the parent is known to
be public: `equals`, `hashCode` and `toString`, and parents declared in the same file. Also not
reported: methods with a comment above them or in their body (other than an IDE stub marker),
which explains why they exist; `equals`, `hashCode` and `toString` in annotated classes (they
may exist to stop Lombok or a similar generator); and methods without `@Override` (a
same-named method with other parameter types is an overload that narrows what is accepted)."#,
    ..RuleMeta::new(
        "java/useless-override",
        "java",
        "Override that only calls super",
    )
};

pub struct UselessOverride;

impl<'t> JavaRule<'t> for UselessOverride {
    fn meta(&self) -> &'static RuleMeta {
        &META
    }

    fn kinds(&self) -> &'static [&'static str] {
        &["method_declaration"]
    }

    fn check(&mut self, node: Node<'t>, ctx: &Ctx<'t>) {
        let Some(body) = node.field(Field::Body) else {
            return;
        };
        // One statement, possibly with a few comments.
        if !(1..=4).contains(&body.named_child_count()) {
            return;
        }
        let Some(stmt) = util::single_statement(body) else {
            return;
        };
        let call = match kind(stmt) {
            "return_statement" | "expression_statement" => syntax::first_named_child(stmt),
            _ => None,
        };
        let Some(call) = call.map(syntax::strip_parens) else {
            return;
        };
        if kind(call) != "method_invocation"
            || call.field(Field::Object).is_none_or(|o| kind(o) != "super")
        {
            return;
        }
        let name = ctx.name_of(node);
        if ctx.call_name(call) != Some(name) {
            return;
        }
        // Same parameters, same order.
        let params: Vec<Node<'t>> = syntax::parameters(node).collect();
        if util::arg_count(call) != params.len() {
            return;
        }
        for (p, a) in params.iter().zip(util::args(call)) {
            let pname = match kind(*p) {
                "formal_parameter" => p.field(Field::Name),
                "spread_parameter" => named_children(*p)
                    .find(|c| kind(*c) == "variable_declarator")
                    .and_then(|d| d.field(Field::Name)),
                _ => None,
            };
            let Some(pname) = pname else {
                return;
            };
            if kind(a) != "identifier" || ctx.text(a) != ctx.text(pname) {
                return;
            }
            if syntax::annotations(*p).next().is_some() {
                return;
            }
        }
        // Only `@Override`, no other modifier that changes something.
        let mut has_override = false;
        for (_, aname) in util::annotation_names(ctx, node) {
            if aname == "Override" {
                has_override = true;
            } else {
                return;
            }
        }
        if !has_override
            || ["final", "synchronized", "strictfp", "native"]
                .iter()
                .any(|m| syntax::has_modifier(node, m))
        {
            return;
        }
        // A comment in the body (other than an IDE stub marker) explains a placeholder.
        if syntax::children(body).any(|c| {
            syntax::is_comment(c) && !ctx.text(c).to_ascii_lowercase().contains("auto-generated")
        }) {
            return;
        }
        let Some(class) = ctx.enclosing_class(node) else {
            return;
        };
        let object_method = matches!(
            (name, params.len()),
            ("equals", 1) | ("hashCode", 0) | ("toString", 0)
        );
        if object_method && (syntax::annotations(class).next().is_some() || ctx.has_lombok(class)) {
            return;
        }
        // The override must not be more visible than the method it overrides: re-declaring a
        // method `public`, or `protected` in another package than the parent's (which opens it to
        // this package), is a deliberate way to expose it.
        let vis = visibility(node);
        let widens = match same_file_parent_visibility(ctx, class, node, name) {
            Some(p) => p < vis,
            None if object_method => false,
            None => match vis {
                3 => true,
                2 => {
                    // JUnit 3 hooks are protected by convention, never re-exported.
                    let junit_hook = matches!(name, "setUp" | "tearDown") && params.is_empty();
                    !junit_hook && !superclass_in_same_package(ctx, class)
                }
                _ => false,
            },
        };
        if widens || util::has_leading_comment(ctx, node) {
            return;
        }
        let Some(name_node) = ctx.name_node(node) else {
            return;
        };
        ctx.emit(
            name_node,
            format!(
                "Remove this override: it only calls `super.{name}(..)` with the same arguments"
            ),
        );
    }
}

fn visibility(m: Node<'_>) -> u8 {
    if syntax::has_modifier(m, "public") {
        3
    } else if syntax::has_modifier(m, "protected") {
        2
    } else if syntax::has_modifier(m, "private") {
        0
    } else {
        1
    }
}

/// The visibility of the method `m` overrides when it is declared in a superclass of this file
/// (same name and parameter types as written).
fn same_file_parent_visibility<'t>(
    ctx: &Ctx<'t>,
    class: Node<'t>,
    m: Node<'t>,
    name: &str,
) -> Option<u8> {
    let sup = class
        .field(Field::Superclass)
        .and_then(syntax::first_named_child)?;
    let base = if kind(sup) == "generic_type" {
        syntax::first_named_child(sup)?
    } else {
        sup
    };
    let t = ctx.resolve_type(base)?;
    let fqn = t.fqn()?;
    let src = ctx.source();
    let root = ctx.root();
    let params = param_types(ctx, m);
    // Look for the class among the top-level and nested classes of this file (bounded: type
    // declarations only).
    let mut stack = vec![root];
    while let Some(n) = stack.pop() {
        let body = if n.id() == root.id() {
            Some(n)
        } else {
            n.field(Field::Body)
        };
        let Some(body) = body else {
            continue;
        };
        for c in named_children(body) {
            if !syntax::is_type_declaration(c) {
                continue;
            }
            if kind(c) == "class_declaration" && ctx.class_fqn(c).as_deref() == Some(fqn) {
                let cb = c.field(Field::Body)?;
                return ctx
                    .members(cb)
                    .find(|pm| {
                        kind(*pm) == "method_declaration"
                            && syntax::name_of(*pm, src) == name
                            && param_types(ctx, *pm) == params
                    })
                    .map(visibility);
            }
            stack.push(c);
        }
    }
    None
}

/// The parameter types of a method as written.
fn param_types<'t>(ctx: &Ctx<'t>, m: Node<'t>) -> Vec<&'t str> {
    syntax::parameters(m)
        .map(|p| {
            p.field(Field::Type)
                .or_else(|| syntax::first_named_child(p))
                .map(|t| ctx.text(t))
                .unwrap_or("")
        })
        .collect()
}

/// Whether the superclass of `class` (or the type an anonymous class extends) provably belongs
/// to the package of this file.
fn superclass_in_same_package<'t>(ctx: &Ctx<'t>, class: Node<'t>) -> bool {
    let ty = if kind(class) == "object_creation_expression" {
        class.field(Field::Type)
    } else {
        class
            .field(Field::Superclass)
            .and_then(syntax::first_named_child)
    };
    let Some(mut ty) = ty else {
        return false;
    };
    if kind(ty) == "generic_type" {
        match syntax::first_named_child(ty) {
            Some(b) => ty = b,
            None => return false,
        }
    }
    let text: String = ctx
        .text(ty)
        .chars()
        .filter(|c| !c.is_whitespace())
        .collect();
    let package = ctx.package_name().unwrap_or("");
    let first = text.split('.').next().unwrap_or("");
    if first.starts_with(|c: char| c.is_ascii_lowercase()) {
        // Package-qualified name.
        return text.rsplit_once('.').is_some_and(|(pkg, _)| pkg == package);
    }
    // A nested type is in the package of its outermost type.
    let outer = first;
    let root = ctx.root();
    let declared_here = named_children(root)
        .any(|c| syntax::is_type_declaration(c) && syntax::name_of(c, ctx.source()) == outer);
    if declared_here {
        return true;
    }
    for i in ctx.imports() {
        if i.is_static {
            continue;
        }
        if i.is_wildcard {
            // The name could come from that package.
            return false;
        }
        if i.simple_name() == outer {
            return i.qualifier() == package;
        }
    }
    // Not imported: the same package, unless it is a `java.lang` class.
    !crate::resolve::is_known_class(&format!("java.lang.{outer}"))
}
