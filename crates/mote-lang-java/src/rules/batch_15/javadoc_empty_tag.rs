//! `java/javadoc-empty-tag` — `@param x`, `@return`, `@throws E` or `@deprecated` without a
//! description.

use super::util;
use crate::prelude::*;

pub static META: RuleMeta = RuleMeta {
    kind: RuleKind::CodeSmell,
    quality: Quality::Maintainability,
    severity: Severity::Low,
    status: RuleStatus::Stable,
    default_enabled: false,
    tags: &["conventions", "documentation"],
    remediation_minutes: 2,
    description: r#"Detects block tags of a documentation comment that carry no description:
`@param` with only the parameter name, `@throws` / `@exception` with only the exception type,
and `@return` or `@deprecated` with nothing after them.

**Why it matters.** An empty tag looks like documentation but says nothing: the generated
page lists the parameter with a blank explanation, and the `@deprecated` note gives users no
replacement to move to. It usually means the tag was generated by an IDE and never filled in.
Either the tag has something to say, or it can go.

**How to fix.** Write the description, or delete the tag.

```java
// Noncompliant
/**
 * Moves the cursor.
 *
 * @param steps
 * @return
 * @throws IOException
 */

// Compliant
/**
 * Moves the cursor.
 *
 * @param steps how far to move; negative values move backwards
 * @return the new position
 * @throws IOException if the underlying stream fails
 */
```

A description may continue on the following lines; it is empty only when the next tag or the
end of the comment comes first. Lines inside `<pre>` blocks and inside inline tags such as
`{@code …}` are not read as tags. Other block tags (`@see`, `@since`, `@author`, custom tags)
are not checked. The rule is off by default: it is part of the `conventions` profile."#,
    ..RuleMeta::new(
        "java/javadoc-empty-tag",
        "java",
        "Javadoc tag without a description",
    )
};

pub struct JavadocEmptyTag;

/// A block tag being read: the span to report, its name, and whether a description was seen.
struct Tag<'s> {
    start: usize,
    end: usize,
    name: &'s str,
    described: bool,
}

/// Whether the tag needs a description (and, for some, which word is the name it documents).
fn checked(tag: &str) -> Option<bool> {
    match tag {
        "param" | "throws" | "exception" => Some(true),
        "return" | "deprecated" => Some(false),
        _ => None,
    }
}

/// Whether `haystack` contains the ASCII `needle`, ignoring ASCII case.
fn contains_ignore_case(haystack: &str, needle: &str) -> bool {
    haystack
        .as_bytes()
        .windows(needle.len())
        .any(|w| w.eq_ignore_ascii_case(needle.as_bytes()))
}

impl JavadocEmptyTag {
    fn report<'t>(ctx: &Ctx<'t>, tag: Option<Tag<'_>>) {
        let Some(tag) = tag else {
            return;
        };
        if tag.described || checked(tag.name).is_none() {
            return;
        }
        ctx.emit_range(
            Span::new(tag.start, tag.end),
            format!("Describe this `@{}` tag, or remove it", tag.name),
        );
    }
}

impl<'t> JavaRule<'t> for JavadocEmptyTag {
    fn meta(&self) -> &'static RuleMeta {
        &META
    }

    fn kinds(&self) -> &'static [&'static str] {
        &["block_comment"]
    }

    fn check(&mut self, node: Node<'t>, ctx: &Ctx<'t>) {
        let text = ctx.text(node);
        if !text.contains('@') || !util::is_doc_comment(text) || !text.ends_with("*/") {
            return;
        }
        let Some(inner) = text.get(3..text.len() - 2) else {
            return;
        };
        let base = node.start_byte() + 3;
        let mut current: Option<Tag<'t>> = None;
        let mut in_pre = false;
        let mut braces: i64 = 0;
        let mut line_start = 0;
        for line in inner.split('\n') {
            let line_off = line_start;
            line_start += line.len() + 1;
            // Leading blanks and the `*` margin.
            let after_ws = line.trim_start();
            let after_stars = after_ws.trim_start_matches('*');
            let content = after_stars.trim_start();
            let content_off = line_off + (line.len() - content.len());
            let content = content.trim_end();
            let reading_tags = !in_pre && braces == 0;
            if reading_tags && content.starts_with('@') {
                let word_len = content[1..]
                    .bytes()
                    .take_while(u8::is_ascii_alphabetic)
                    .count();
                if word_len > 0 {
                    Self::report(ctx, current.take());
                    let name = &content[1..1 + word_len];
                    let mut rest = &content[1 + word_len..];
                    let mut end = content_off + 1 + word_len;
                    if checked(name) == Some(true) {
                        // Skip the documented name (`x`, `<T>`, `IOException`).
                        let ws = rest.len() - rest.trim_start().len();
                        let word = rest[ws..]
                            .find(char::is_whitespace)
                            .unwrap_or(rest.len() - ws);
                        end += ws + word;
                        rest = &rest[ws + word..];
                    }
                    current = Some(Tag {
                        start: base + content_off,
                        end: base + end,
                        name,
                        described: !rest.trim().is_empty(),
                    });
                }
            } else if let Some(tag) = current.as_mut() {
                if !content.is_empty() {
                    tag.described = true;
                }
            }
            if contains_ignore_case(content, "<pre") {
                in_pre = true;
            }
            if contains_ignore_case(content, "</pre") {
                in_pre = false;
            }
            for b in content.bytes() {
                match b {
                    b'{' => braces += 1,
                    b'}' => braces = (braces - 1).max(0),
                    _ => {}
                }
            }
        }
        Self::report(ctx, current);
    }
}
